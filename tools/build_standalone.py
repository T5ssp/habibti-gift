#!/usr/bin/env python3
"""Compile local styles, scripts, fonts and illustrations into a portable gift.

Run after changing frontend files. No dependencies, network requests or minifier.
The runtime export injects the visitor's sanitized personal data into this source.
"""
import base64
import json
import mimetypes
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def data_url(path):
    mime = {".woff2": "font/woff2", ".webp": "image/webp", ".svg": "image/svg+xml"}.get(path.suffix)
    mime = mime or mimetypes.guess_type(str(path))[0] or "application/octet-stream"
    return "data:" + mime + ";base64," + base64.b64encode(path.read_bytes()).decode("ascii")


def main():
    source = (ROOT / "index.html").read_text()
    images = {path.stem: data_url(path) for path in sorted((ROOT / "assets/images").glob("*.webp"))}

    def inline_style(match):
        path = ROOT / match[1]
        css = path.read_text()

        def inline_url(url):
            value = url[1].strip("\"'")
            if value.startswith(("data:", "http:", "https:", "#")):
                return url[0]
            asset = (path.parent / value).resolve()
            assert asset.is_relative_to(ROOT) and asset.is_file(), asset
            if asset.suffix == ".webp":
                return "var(--asset-" + asset.stem + ")"
            return 'url("' + data_url(asset) + '")'

        css = re.sub(r"url\(([^)]+)\)", inline_url, css)
        return "<style>\n" + css + "\n</style>"

    source = re.sub(r'<link rel="stylesheet" href="([^"]+)">', inline_style, source)
    source = re.sub(r'<script[^>]+data-export-source[^>]*></script>\s*', "", source)

    def inline_script(match):
        code = (ROOT / match[1]).read_text().replace("</script", "<\\/script")
        return "<script>\n" + code + "\n</script>"

    source = re.sub(r'<script src="([^"]+)"></script>', inline_script, source)
    source = re.sub(r'src="assets/images/([^"/]+)\.webp"', r'data-bundled-image="\1"', source)
    source = source.replace('href="assets/images/heart.svg"', 'href="' + data_url(ROOT / "assets/images/heart.svg") + '"')
    # One copy per illustration; CSS custom properties and JS share the same data.
    setup = "window.HabibtiAssets=" + json.dumps(images, separators=(",", ":")) + ";\n"
    setup += "Object.entries(window.HabibtiAssets).forEach(([name,url])=>document.documentElement.style.setProperty('--asset-'+name,'url(\"'+url+'\")'));\n"
    setup += "document.addEventListener('DOMContentLoaded',()=>document.querySelectorAll('[data-bundled-image]').forEach(img=>img.src=window.HabibtiAssets[img.dataset.bundledImage]),{once:true});"
    source = source.replace('<meta charset="UTF-8">', '<meta charset="UTF-8">\n<script>' + setup + '</script>', 1)
    assert not re.search(r'<(?:script|link)[^>]+(?:src|href)="assets/', source)
    output = ROOT / "dist"
    output.mkdir(exist_ok=True)
    (output / "habibti-standalone.html").write_text(source)
    # External JS can carry literal HTML. JSON escaping makes it data, never code.
    (ROOT / "assets/js/export-source.js").write_text(
        "/* Generated by tools/build_standalone.py. Do not edit by hand. */\n"
        + "window.HabibtiStandaloneSource=" + json.dumps(source, ensure_ascii=False) + ";\n"
    )
    print(f"Built portable gift: {len(source.encode()):,} bytes; {len(images)} illustrations, local fonts, styles and scripts included.")


if __name__ == "__main__":
    main()
